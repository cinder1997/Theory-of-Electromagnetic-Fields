%% 计算圆形载流回路轴线上的磁场幅度
clear;clc;close all;
I=1;               %电流大小
a=0:0.1:10;         %载流回路的半径
z=2;               %载流回路轴线上的高度
mu0=4*pi*1e-7;
B=mu0*I/2.*(a.^2./sqrt(z^2+a.^2).^3);
plot(a,B);
xlabel('半径');ylabel('磁场幅度');
title('圆形载流回路轴线上的磁场幅度与回路半径的关系');
%在远场区域，回路面积越大产生的磁场强度越大；在近场区域，回路面积越大产生的磁场强度越小